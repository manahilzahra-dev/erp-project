export default function Sidebar() {
  const pathname = usePathname();
  const { user } = useAuth();

  const visibleItems = navItems.filter((item) =>
    user ? item.roles.includes(user.role) : false
  );

  // Senior approach: Group items by section
  const sections: { name: string; items: NavItem[] }[] = [];
  visibleItems.forEach((item) => {
    const sectionName = item.section || "Other";
    const existing = sections.find((s) => s.name === sectionName);
    if (existing) existing.items.push(item);
    else sections.push({ name: sectionName, items: [item] });
  });

  return (
    <aside className="w-[248px] h-screen sticky top-0 bg-[var(--surface)] border-r border-[var(--border)] flex flex-col">
      {/* Logo */}
      <div className="h-14 flex items-center px-4 border-b border-[var(--border)]">
        <Logo size="sm" />
      </div>

      {/* Nav */}
      <nav className="flex-1 overflow-y-auto px-3 py-4">
        {sections.map((section, idx) => (
          <div key={section.name} className={idx > 0 ? "mt-6" : ""}>
            <p className="erp-label px-3 mb-1.5">{section.name}</p>
            <div className="space-y-0.5">
              {section.items.map((item) => {
                const isActive =
                  item.href === "/dashboard"
                    ? pathname === "/dashboard"
                    : pathname.startsWith(item.href);

                return (
                  <Link
                    key={item.href}
                    href={item.href}
                    className={`erp-nav-item ${isActive ? "erp-nav-item-active" : ""}`}
                  >
                    {item.icon}
                    <span className="flex-1">{item.label}</span>
                    {isActive && (
                      <span className="w-1 h-1 rounded-full bg-[var(--brand-600)]"></span>
                    )}
                  </Link>
                );
              })}
            </div>
          </div>
        ))}
      </nav>

      {/* Footer */}
      <div className="p-3 border-t border-[var(--border)]">
        <div className="px-2.5 py-2">
          <p className="text-[11px] font-medium text-[var(--text-muted)]">
            v1.0.0 <span className="text-[var(--text-secondary)]">·</span> 2026
          </p>
        </div>
      </div>
    </aside>
  );
}